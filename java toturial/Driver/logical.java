package Driver;

public class logical {
    public static void main(String[] args) {
        //logical operator
        int a = 10;
        int b = 20;
        System.out.println(a > b && a < b); //&& operator
        System.out.println(a > b || a < b); //|| operator
        System.out.println(!(a > b)); //! operator
    }
}
