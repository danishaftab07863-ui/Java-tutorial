public class conditional {
    public static void main(String[] args) {
        //conitional statement
        int apple = 30;
        int orange = 20;
        if (apple > orange) {
            System.out.println("Apple is greater than Orange");
        } else if (apple < orange) {
            System.out.println("Apple is less than Orange");
        } else {
            System.out.println("Apple is equal to Orange");
        
        }
    } 
}
